import {
  buildMethodsText,
  usesRequestedModelIds,
  type MethodsFacts,
} from '../../../../src/features/export/methodsBoilerplate';

/** 記録が何も無いプロジェクト（全文が既定の分岐・プレースホルダのまま） */
function makeFacts(overrides: Partial<MethodsFacts> = {}): MethodsFacts {
  return {
    toolVersion: null,
    aiDraft: false,
    draftModelIds: [],
    draftProviders: [],
    modelIds: [],
    modelIdsIncludeRequested: false,
    providers: [],
    includedStudyCount: 0,
    extractedStudyCount: 0,
    partialStudyCount: 0,
    pilotStudyCount: 0,
    revisedAfterPilot: false,
    formRevisionCount: 0,
    scannedDocumentCount: 0,
    pilotRevisionCount: 0,
    chatAssistDecisionCount: 0,
    unverifiedCellCount: 0,
    humanWithAiAnnotatorCount: 0,
    humanIndependentAnnotatorCount: 0,
    hasConsensus: false,
    ...overrides,
  };
}

/** 典型的なプロジェクト（AI 草案・パイロット後に改訂・全研究で事前抽出・全セル検証済み） */
function typicalFacts(overrides: Partial<MethodsFacts> = {}): MethodsFacts {
  return makeFacts({
    toolVersion: '2.0.0',
    aiDraft: true,
    draftModelIds: ['gemini-3.8-flash'],
    draftProviders: ['Gemini'],
    modelIds: ['gemini-3.8-flash-001'],
    providers: ['Gemini'],
    includedStudyCount: 10,
    extractedStudyCount: 10,
    pilotStudyCount: 3,
    revisedAfterPilot: true,
    formRevisionCount: 1,
    humanWithAiAnnotatorCount: 1,
    ...overrides,
  });
}

describe('buildMethodsText: 1 段落目（ツールとフォーム）', () => {
  test('見出しはプレーンテキストで先頭に付け、Markdown 太字を含めない', () => {
    const en = buildMethodsText('en', 'single', makeFacts());
    expect(en.text.startsWith('Data extraction. Data were extracted using')).toBe(true);
    expect(en.text).not.toContain('**');
    const ja = buildMethodsText('ja', 'single', makeFacts());
    expect(
      ja.text.startsWith(
        'データ抽出. データ抽出には、大規模言語モデル（LLM）による抽出支援と人間による検証を行う',
      ),
    ).toBe(true);
  });

  test('tool_version が反映され、null なら {{tool_version}} が残る', () => {
    const withVersion = buildMethodsText('en', 'single', makeFacts({ toolVersion: '1.4.0' }));
    expect(withVersion.text).toContain(
      'version 1.4.0 (https://github.com/youkiti/sr-data-extraction-plugin)',
    );
    expect(withVersion.unresolved).not.toContain('tool_version');
    expect(buildMethodsText('en', 'single', makeFacts()).unresolved).toContain('tool_version');
  });

  test('AI の草案の記録が無いときは「著者らが作成した」とし、モデル名・サンプル数を書かない', () => {
    const en = buildMethodsText('en', 'single', makeFacts());
    expect(en.text).toContain('The data extraction form was developed by the authors.');
    expect(en.text).not.toContain('draft data extraction form');
    expect(en.unresolved).not.toContain('n_sample');
    const ja = buildMethodsText('ja', 'single', makeFacts());
    expect(ja.text).toContain('抽出フォームは著者らが作成した。');
    expect(ja.text).not.toContain('草案');
  });

  test('AI の草案の記録があり草案のモデルが取れるときは、草案のモデルと provider を書く', () => {
    const facts = makeFacts({
      aiDraft: true,
      draftModelIds: ['gemini-3.8-flash', 'gemini-3.5-pro'],
      draftProviders: ['Gemini'],
      modelIds: ['other-model'],
    });
    const en = buildMethodsText('en', 'single', facts);
    expect(en.text).toContain(
      'A draft data extraction form was generated by an LLM (gemini-3.8-flash, gemini-3.5-pro, accessed via the Gemini API) from the review protocol and {{n_sample}} sample articles, and was reviewed and revised as needed by the authors.',
    );
    const ja = buildMethodsText('ja', 'single', facts);
    expect(ja.text).toContain(
      '抽出フォームの草案は、レビュープロトコルとサンプル論文 {{n_sample}} 本をもとに LLM（gemini-3.8-flash, gemini-3.5-pro、Gemini API 経由）が作成し、著者らが内容を確認し、必要に応じて修正した。',
    );
  });

  test('AI の草案の記録はあるが草案のモデルが取れないときは、モデル名を書かない', () => {
    const facts = makeFacts({ aiDraft: true, modelIds: ['extract-model'] });
    const en = buildMethodsText('en', 'single', facts);
    expect(en.text).toContain(
      'A draft data extraction form was generated by an LLM from the review protocol and {{n_sample}} sample articles,',
    );
    expect(en.unresolved).not.toContain('draft_model_id');
    const ja = buildMethodsText('ja', 'single', facts);
    expect(ja.text).toContain('サンプル論文 {{n_sample}} 本をもとに LLM が作成し、');
  });

  test.each([
    [
      'パイロット後に改訂した',
      { pilotStudyCount: 3, revisedAfterPilot: true },
      'The form was piloted on 3 studies and revised before full extraction.',
      'フォームは 3 本の研究でパイロット抽出を行い、改訂したうえで本抽出に用いた。',
    ],
    [
      'パイロットのみ（その後の版なし）',
      { pilotStudyCount: 2, revisedAfterPilot: false, formRevisionCount: 1 },
      'The form was piloted on 2 studies before full extraction.',
      'フォームは 2 本の研究でパイロット抽出を行ったうえで本抽出に用いた。',
    ],
    [
      'パイロットなし・版が 2 つ以上',
      { formRevisionCount: 2 },
      'The form was revised 2 times during the review.',
      'フォームはレビューの過程で 2 回改訂した。',
    ],
  ])('パイロットと改訂の文: %s', (_label, overrides, en, ja) => {
    expect(buildMethodsText('en', 'single', makeFacts(overrides)).text).toContain(en);
    expect(buildMethodsText('ja', 'single', makeFacts(overrides)).text).toContain(ja);
  });

  test('パイロットも改訂も無いときは、パイロット・改訂の文を出さない', () => {
    const en = buildMethodsText('en', 'single', makeFacts());
    expect(en.text).not.toContain('piloted');
    expect(en.text).not.toContain('was revised');
    expect(en.unresolved).not.toContain('n_pilot');
    expect(buildMethodsText('ja', 'single', makeFacts()).text).not.toContain('パイロット');
  });
});

describe('buildMethodsText: 2 段落目（事前抽出）', () => {
  test('全採用研究で事前抽出に成功したときは「すべて」とし、事前抽出のモデルを書く', () => {
    const en = buildMethodsText('en', 'single', typicalFacts());
    expect(en.text).toContain(
      'For all 10 included studies, an LLM (gemini-3.8-flash-001, accessed via the Gemini API) pre-extracted the form items from the full-text PDF',
    );
    expect(en.text).not.toContain('remaining');
    const ja = buildMethodsText('ja', 'single', typicalFacts());
    expect(ja.text).toContain(
      '採用研究 10 本すべてについて、LLM（gemini-3.8-flash-001、Gemini API 経由）が全文 PDF から',
    );
  });

  test('一部の研究で失敗したときは「n 本のうち m 本」とし、残りの研究の文を足す', () => {
    const facts = typicalFacts({ extractedStudyCount: 8 });
    const en = buildMethodsText('en', 'single', facts);
    expect(en.text).toContain('For 8 of the 10 included studies, an LLM');
    expect(en.text).toContain(
      'For the remaining 2 studies, LLM pre-extraction was not run or did not complete successfully.',
    );
    const ja = buildMethodsText('ja', 'single', facts);
    expect(ja.text).toContain('採用研究 10 本のうち 8 本について、');
    expect(ja.text).toContain(
      '残る 2 本では、LLM による事前抽出を実行していないか、正常に完了しなかった。',
    );
  });

  test('事前抽出の記録が無いときは研究数・モデルをプレースホルダのまま残し、残りの研究の文を出さない', () => {
    const result = buildMethodsText('en', 'single', makeFacts());
    expect(result.text).toContain(
      'For {{n_extracted}} of the {{n_included}} included studies, an LLM ({{model_id}}, accessed via the {{provider}} API)',
    );
    expect(result.text).not.toContain('remaining');
    expect(result.unresolved).toEqual(
      expect.arrayContaining(['n_extracted', 'n_included', 'model_id', 'provider']),
    );
  });

  test('全項目の事前抽出を確かめられない研究があるときだけ、その旨の文を足す', () => {
    const facts = typicalFacts({ partialStudyCount: 3 });
    expect(buildMethodsText('en', 'single', facts).text).toContain(
      'For 3 of the pre-extracted studies, pre-extraction may not have covered every item, because the run was limited to selected items or part of the LLM output was discarded or could not be saved.',
    );
    expect(buildMethodsText('ja', 'single', facts).text).toContain(
      '事前抽出した研究のうち 3 本では、実行の対象を一部の項目に限った、または LLM 出力の一部を破棄した・保存できなかったため、事前抽出が全項目に及んでいない可能性がある。',
    );
    expect(buildMethodsText('en', 'single', typicalFacts()).text).not.toContain('may not have covered');
  });

  test('事前抽出のモデル・provider が複数のときは「, 」区切りで列挙する', () => {
    const facts = typicalFacts({
      modelIds: ['gemini-3.8-flash-001', 'gpt-test'],
      providers: ['Gemini', 'OpenRouter'],
    });
    expect(buildMethodsText('en', 'single', facts).text).toContain(
      'an LLM (gemini-3.8-flash-001, gpt-test, accessed via the Gemini, OpenRouter API)',
    );
  });
});

describe('buildMethodsText: 検証（単一レビュアー）', () => {
  test('単一レビュアーの文は「すべての AI 抽出値」と言い切らない', () => {
    const en = buildMethodsText('en', 'single', typicalFacts());
    expect(en.text).toContain(
      'One reviewer ({{reviewer_initials}}) checked the AI-extracted values against the highlighted source text and accepted, corrected, or rejected each value, or marked the item as not reported.',
    );
    expect(en.text).not.toContain('Two reviewers');
    expect(en.unresolved).not.toContain('adjudicator_initials');
    const ja = buildMethodsText('ja', 'single', typicalFacts());
    expect(ja.text).toContain(
      'レビュアー 1 名（{{reviewer_initials}}）が AI 抽出値を原文と照合して、承認・修正・棄却・未報告のいずれかを判定した。',
    );
    expect(ja.text).not.toContain('すべての AI 抽出値');
  });

  test('未検証のセルが 0 件なら「すべての項目に明示的な判定」の文を出す', () => {
    const en = buildMethodsText('en', 'single', typicalFacts());
    expect(en.text).toContain(
      'every item — including accepted values — required an explicit decision by the reviewer',
    );
    expect(en.unresolved).not.toContain('n_unverified');
    expect(buildMethodsText('ja', 'single', typicalFacts()).text).toContain(
      '承認を含むすべての項目に明示的な判定操作を必須としたため',
    );
  });

  test('未検証のセルが 1 件以上なら、すべてを判定したとは書かず件数を書く', () => {
    const facts = typicalFacts({ unverifiedCellCount: 4 });
    const en = buildMethodsText('en', 'single', facts);
    expect(en.text).not.toContain('every item — including accepted values — required');
    expect(en.text).toContain(
      'at the time of export, 4 cells had not been verified and were left empty.',
    );
    const ja = buildMethodsText('ja', 'dual', facts);
    expect(ja.text).not.toContain('すべての項目に明示的な判定操作を必須とした');
    expect(ja.text).toContain(
      'ただし、エクスポート時点で 4 件のセルは未検証のままであり、空欄として出力した。',
    );
  });

  test('監査証跡の文は常に出し、supplement_ref はプレースホルダのまま', () => {
    const result = buildMethodsText('en', 'single', typicalFacts());
    expect(result.text).toContain('the complete audit trail is provided in {{supplement_ref}}.');
    expect(result.unresolved).toEqual(['n_sample', 'reviewer_initials', 'supplement_ref']);
  });
});

describe('buildMethodsText: 検証（二重独立）', () => {
  test('human_independent の行が無いときは「2 名が AI の値を独立に検証」', () => {
    const facts = typicalFacts({ humanWithAiAnnotatorCount: 2, hasConsensus: true });
    const en = buildMethodsText('en', 'dual', facts);
    expect(en.text).toContain(
      'Two reviewers ({{reviewer_initials}}) independently verified the AI-extracted values against the highlighted source text',
    );
    expect(en.text).not.toContain('One reviewer');
    expect(buildMethodsText('ja', 'dual', facts).text).toContain(
      'レビュアー 2 名（{{reviewer_initials}}）が独立に、AI 抽出値を原文と照合して',
    );
  });

  test('human_with_ai と human_independent の両方があるときは、第 2 のレビュアーが AI を見ずに抽出したと書く', () => {
    const facts = typicalFacts({ humanWithAiAnnotatorCount: 1, humanIndependentAnnotatorCount: 1 });
    expect(buildMethodsText('en', 'dual', facts).text).toContain(
      'and the second reviewer extracted the data independently without seeing the AI output.',
    );
    expect(buildMethodsText('ja', 'dual', facts).text).toContain(
      '第 2 のレビュアーは AI の出力を見ずに独立に抽出した。',
    );
  });

  test('human_independent の行だけのときは、2 名とも AI を見ずに抽出したと書く', () => {
    const facts = typicalFacts({ humanWithAiAnnotatorCount: 0, humanIndependentAnnotatorCount: 2 });
    expect(buildMethodsText('en', 'dual', facts).text).toContain(
      'Two reviewers ({{reviewer_initials}}) independently extracted the data without seeing the AI output.',
    );
    expect(buildMethodsText('ja', 'dual', facts).text).toContain(
      'レビュアー 2 名（{{reviewer_initials}}）が、AI の出力を見ずに独立に抽出した。',
    );
  });

  test('consensus の行があるときだけ裁定の文を出し、無いときは未解消と書く', () => {
    const withConsensus = buildMethodsText('en', 'dual', typicalFacts({ hasConsensus: true }));
    expect(withConsensus.text).toContain('a third reviewer ({{adjudicator_initials}})');
    expect(withConsensus.unresolved).toContain('adjudicator_initials');
    const without = buildMethodsText('en', 'dual', typicalFacts());
    expect(without.text).toContain(
      'At the time of export, no consensus values (final values after resolving disagreements) had been recorded.',
    );
    expect(without.unresolved).not.toContain('adjudicator_initials');
    expect(buildMethodsText('ja', 'dual', typicalFacts({ hasConsensus: true })).text).toContain(
      '第 3 のレビュアー（{{adjudicator_initials}}）が裁定して',
    );
    expect(buildMethodsText('ja', 'dual', typicalFacts()).text).toContain(
      'エクスポート時点では、コンセンサス値（不一致を解消した最終値）は記録していなかった。',
    );
  });
});

describe('buildMethodsText: オプション文', () => {
  test('scannedDocumentCount > 0 のときだけスキャン PDF の文を連結する', () => {
    expect(buildMethodsText('en', 'single', makeFacts()).text).not.toContain('scanned PDFs');
    expect(buildMethodsText('en', 'single', makeFacts({ scannedDocumentCount: 3 })).text).toContain(
      'For 3 studies available only as scanned PDFs without a text layer',
    );
    expect(buildMethodsText('ja', 'single', makeFacts({ scannedDocumentCount: 2 })).text).toContain(
      'テキスト層を持たないスキャン PDF のみ入手可能であった 2 本については',
    );
  });

  test.each(['ja', 'en'] as const)('改訂回数が正のときだけ正典の追加文を末尾へ付ける（%s）', (language) => {
    const sentence =
      language === 'ja'
        ? 'パイロットでの判定に基づき、抽出指示を 2 回改訂した。改訂案は LLM が項目の抽出指示と例に限って作成し、著者らが確認・承認したうえで本抽出に用いた。'
        : "Based on the reviewers' judgments during the pilot, the extraction instructions were revised 2 times; the LLM drafted revision proposals limited to item instructions and examples, which the authors reviewed and approved before full extraction.";
    const withRevision = buildMethodsText(language, 'single', makeFacts({ pilotRevisionCount: 2 }));
    expect(withRevision.text.endsWith(sentence)).toBe(true);
    expect(withRevision.unresolved).not.toContain('n_pilot_revision');
    expect(buildMethodsText(language, 'single', makeFacts()).text).not.toContain(sentence);
  });

  test.each(['en', 'ja'] as const)('質問後の判定があるときだけ正典のオプション文を末尾へ加える: %s', (language) => {
    const sentence =
      language === 'en'
        ? 'During verification, reviewers could additionally ask an LLM questions about the full text of the study under review; answers were constrained to verbatim quotations that the tool located in the source text, were not entered into the dataset automatically, and decisions made after such questions were flagged in the audit trail.'
        : '検証中、レビュアーは検証対象の研究の本文について LLM に質問することもできた。回答にはツールが原文中で照合した逐語的な引用を必須とし、回答が自動でデータに入力されることはなく、質問後の判定は監査証跡に印を付けて記録した。';
    for (const workflow of ['single', 'dual'] as const) {
      expect(buildMethodsText(language, workflow, makeFacts()).text).not.toContain(sentence);
      expect(
        buildMethodsText(language, workflow, makeFacts({ chatAssistDecisionCount: 2 })).text.endsWith(
          sentence,
        ),
      ).toBe(true);
    }
  });
});

