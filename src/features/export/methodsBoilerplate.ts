/** 文を言語に合わせてつなぐ（英語は半角スペース、日本語は句点の後に空白を入れない） */
function joinSentences(language: MethodsLanguage, sentences: readonly Sentence[]): string {
  return sentences.map((sentence) => sentence[language]).join(language === 'en' ? ' ' : '');
}

/** §1 1 段落目（ツール + フォームの作成 + パイロットと改訂） */
function paragraph1(facts: MethodsFacts): Sentence[] {
  const sentences: Sentence[] = [TOOL];
  if (!facts.aiDraft) {
    sentences.push(FORM_BY_AUTHORS);
  } else {
    sentences.push(facts.draftModelIds.length > 0 ? DRAFT_WITH_MODEL : DRAFT_WITHOUT_MODEL);
  }
  if (facts.pilotStudyCount > 0) {
    sentences.push(facts.revisedAfterPilot ? PILOT_REVISED : PILOT_ONLY);
  } else if (facts.formRevisionCount > 0) {
    sentences.push(FORM_REVISED);
  }
  return sentences;
}

/** §2.4 二重独立の検証文（人の行の種別で 3 通り）+ 裁定の文 */
function dualVerification(facts: MethodsFacts): Sentence[] {
  let verify = VERIFY_DUAL_WITH_AI;
  if (facts.humanIndependentAnnotatorCount > 0) {
    verify = facts.humanWithAiAnnotatorCount > 0 ? VERIFY_DUAL_MIXED : VERIFY_DUAL_INDEPENDENT;
  }
  return [verify, facts.hasConsensus ? CONSENSUS : NO_CONSENSUS];
}

/** §2 2 段落目（事前抽出 + 届かなかった研究 + 検証 + 未検証のセル + 監査証跡） */
function paragraph2(workflow: MethodsWorkflow, facts: MethodsFacts): Sentence[] {
  const allExtracted =
    facts.includedStudyCount > 0 && facts.extractedStudyCount === facts.includedStudyCount;
  const sentences: Sentence[] = [allExtracted ? PREEXTRACT_ALL : PREEXTRACT_SOME];
  if (facts.extractedStudyCount > 0 && facts.extractedStudyCount < facts.includedStudyCount) {
    sentences.push(NOT_EXTRACTED);
  }
  if (facts.partialStudyCount > 0) {
    sentences.push(PARTIAL_ITEMS);
  }
  sentences.push(...(workflow === 'dual' ? dualVerification(facts) : [VERIFY_SINGLE]));
  sentences.push(facts.unverifiedCellCount > 0 ? SOME_UNVERIFIED : ALL_VERIFIED, AUDIT_TRAIL);
  return sentences;
}

/** 正の数だけを反映する（0 は「反映できない」= {{...}} のまま残す） */
function positiveOrNull(value: number): string | null {
  return value > 0 ? String(value) : null;
}

/** 空配列は反映しない。複数は「, 」区切りで列挙する */
function listOrNull(values: readonly string[]): string | null {
  return values.length > 0 ? values.join(', ') : null;
}

/**
 * モデル名の一部が要求したモデル ID（API が返した実際の版ではない）か。
 * 草案のモデルは常に要求したモデル ID のため、草案の文にモデル名を書いたときも真（カードの説明文の条件）
 */
export function usesRequestedModelIds(facts: MethodsFacts): boolean {
  return facts.modelIdsIncludeRequested || (facts.aiDraft && facts.draftModelIds.length > 0);
}

/** text 中の {{key}} をすべて value に置換する（value が null なら手を付けず {{key}} を残す） */
function applyPlaceholder(text: string, key: string, value: string | null): string {
  if (value === null) {
    return text;
  }
  return text.split(`{{${key}}}`).join(value);
}

/** 残存する {{...}} プレースホルダ名を出現順・重複除去で列挙する */
function findUnresolvedPlaceholders(text: string): string[] {
  const tokens = text.match(/\{\{[a-zA-Z0-9_]+\}\}/g);
  /* istanbul ignore if -- 正典の文案（§1〜2）は reviewer_initials / supplement_ref を
     必ず含み、自動反映しないため、buildMethodsText 経由では未反映 0 件（= match が null）にはならない防御分岐 */
  if (tokens === null) {
    return [];
  }
  const names = tokens.map((token) => token.slice(2, -2));
  return Array.from(new Set(names)); // Set はキー追加順を保持するため出現順のまま重複除去できる
}

/**
 * 論文 Methods セクションの記載例を組み立てる（docs/methods-boilerplate.md §1〜2 の正典どおり）。
 * 記録に合う文だけを選び（issue #381）、自動反映できる実績値はプレースホルダへ埋め込む。
 * n_sample / reviewer_initials / adjudicator_initials / supplement_ref は常に {{...}} のまま残す
 * （§3: ユーザー自身の編集を促す）
 */
export function buildMethodsText(
  language: MethodsLanguage,
  workflow: MethodsWorkflow,
  facts: MethodsFacts,
): BuiltMethodsText {
  const parts = [
    `${HEADING[language]} ${joinSentences(language, paragraph1(facts))}`,
    joinSentences(language, paragraph2(workflow, facts)),
  ];
  if (facts.scannedDocumentCount > 0) {
    parts.push(OPTIONAL_SCANNED[language]);
  }
  if (facts.pilotRevisionCount > 0) {
    parts.push(OPTIONAL_PILOT_REVISION[language]);
  }
  if (facts.chatAssistDecisionCount > 0) {
    parts.push(OPTIONAL_CHAT_ASSIST[language]);
  }
  const values: Record<string, string | null> = {
    tool_version: facts.toolVersion,
    draft_model_id: listOrNull(facts.draftModelIds),
    draft_provider: listOrNull(facts.draftProviders),
    model_id: listOrNull(facts.modelIds),
    provider: listOrNull(facts.providers),
    n_pilot: positiveOrNull(facts.pilotStudyCount),
    n_form_revision: String(facts.formRevisionCount),
    n_included: positiveOrNull(facts.includedStudyCount),
    n_extracted: positiveOrNull(facts.extractedStudyCount),
    n_not_extracted: String(facts.includedStudyCount - facts.extractedStudyCount),
    n_partial: String(facts.partialStudyCount),
    n_unverified: String(facts.unverifiedCellCount),
    n_scanned: positiveOrNull(facts.scannedDocumentCount),
    n_pilot_revision: String(facts.pilotRevisionCount),
  };
  let text = parts.join('\n\n');
  for (const [key, value] of Object.entries(values)) {
    text = applyPlaceholder(text, key, value);
  }
  // n_sample / reviewer_initials / adjudicator_initials / supplement_ref は常に自動反映しない（§3）
  return { text, unresolved: findUnresolvedPlaceholders(text) };
}
